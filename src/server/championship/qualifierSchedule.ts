import type { ChampionshipGameView, QualifierGroupId } from '../../shared/protocol';
import { createGameView } from './schedule';

/** One entrant inside a qualifying group, in seat order. */
export interface QualifierScheduleMember {
  id: string;
  name: string;
}

/** A qualifying group and its five members. */
export interface QualifierGroupSchedule {
  id: QualifierGroupId;
  members: readonly QualifierScheduleMember[];
}

interface QualifierPairing {
  /** 0-based seats inside the group. */
  leftSeat: number;
  rightSeat: number;
  /** Seat that takes red; the orientation balances every player at 2 red / 2 black. */
  redSeat: number;
}

/**
 * Five-round single round-robin for five players, generated by the circle
 * method. Every round has two games and one bye, so combining the same round
 * in both groups yields four games that share no entrant. The orientation is
 * an Eulerian orientation of K5: every player gets exactly two reds and two
 * blacks across their four games.
 */
const QUALIFIER_ROUNDS: readonly (readonly QualifierPairing[])[] = [
  [
    { leftSeat: 1, rightSeat: 4, redSeat: 4 },
    { leftSeat: 2, rightSeat: 3, redSeat: 2 },
  ],
  [
    { leftSeat: 0, rightSeat: 3, redSeat: 3 },
    { leftSeat: 1, rightSeat: 2, redSeat: 1 },
  ],
  [
    { leftSeat: 4, rightSeat: 2, redSeat: 2 },
    { leftSeat: 0, rightSeat: 1, redSeat: 0 },
  ],
  [
    { leftSeat: 3, rightSeat: 1, redSeat: 1 },
    { leftSeat: 4, rightSeat: 0, redSeat: 4 },
  ],
  [
    { leftSeat: 2, rightSeat: 0, redSeat: 0 },
    { leftSeat: 3, rightSeat: 4, redSeat: 3 },
  ],
];

/** Number of scheduling rounds; also the number of concurrency waves. */
export const QUALIFIER_ROUND_COUNT = QUALIFIER_ROUNDS.length;

/**
 * Schedule both qualifying groups upfront. Pair indexes run 1…10 inside each
 * group (two pairings per round), so `ceil(pairIndex / 2)` is the round/wave.
 * Games are appended group by group; ids run g1…g20.
 */
export function buildQualifierGames(
  groups: readonly QualifierGroupSchedule[],
): ChampionshipGameView[] {
  const games: ChampionshipGameView[] = [];

  for (const group of groups) {
    if (group.members.length !== 5) {
      throw new Error(`入围赛 ${group.id} 组必须恰好有 5 位选手`);
    }
    let pairIndex = 0;
    for (const round of QUALIFIER_ROUNDS) {
      for (const pairing of round) {
        pairIndex += 1;
        const left = group.members[pairing.leftSeat];
        const right = group.members[pairing.rightSeat];
        if (!left || !right) {
          throw new Error(`入围赛 ${group.id} 组缺少第 ${pairing.leftSeat + 1} 或第 ${pairing.rightSeat + 1} 席选手`);
        }
        const redIsLeft = pairing.redSeat === pairing.leftSeat;
        const red = redIsLeft ? left : right;
        const black = redIsLeft ? right : left;
        games.push(
          createGameView({
            id: `g${games.length + 1}`,
            pairIndex,
            gameIndex: 1,
            stage: 'qualifier',
            groupId: group.id,
            seriesId: null,
            redId: red.id,
            redName: red.name,
            blackId: black.id,
            blackName: black.name,
          }),
        );
      }
    }
  }

  return games;
}

/** Round/wave (1-based) a scheduled qualifying game belongs to. */
export function qualifierRoundOf(game: Pick<ChampionshipGameView, 'pairIndex'>): number {
  return Math.ceil(game.pairIndex / 2);
}
